<script>
  // Mobile accordion for columns
  const cols = document.querySelectorAll('.fa-col');
  const mq = window.matchMedia('(max-width: 640px)');

  function initAccordions() {
    cols.forEach(col => {
      if (mq.matches) {
        if (!col.hasAttribute('aria-expanded')) col.setAttribute('aria-expanded', 'false');
        const h = col.querySelector('.fa-col-title');
        if (!h.dataset.bound) {
          h.dataset.bound = '1';
          h.tabIndex = 0;
          h.addEventListener('click', () => toggle(col));
          h.addEventListener('keydown', (e) => {
            if (e.key === 'Enter' || e.key === ' ') {
              e.preventDefault();
              toggle(col);
            }
          });
        }
      } else {
        col.removeAttribute('aria-expanded');
      }
    });
  }

  function toggle(col) {
    const open = col.getAttribute('aria-expanded') === 'true';
    col.setAttribute('aria-expanded', String(!open));
  }
  initAccordions();
  window.addEventListener('resize', initAccordions);
</script>
